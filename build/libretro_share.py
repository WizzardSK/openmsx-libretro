# Packs what the libretro core writes to <system>/openmsx/share into a C++
# header: openMSX's share folder with the C-BIOS machines and ROMs added as an
# install puts them (Contrib/cbios in machines, Contrib/cbios-old in
# systemroms/cbios-old, its readme as cbios.txt), so games start on C-BIOS
# with nothing else to download.
#
# The data: for each file a 4-byte little-endian length of its path (relative
# to share, with '/'), the path, an 8-byte length of its contents and the
# contents; all of it compressed with zlib.

import os
import sys
import zlib


def files():
	for root, dirs, names in os.walk('share'):
		dirs.sort()
		for name in sorted(names):
			if name == '.gitignore':
				continue
			path = os.path.join(root, name)
			yield os.path.relpath(path, 'share').replace(os.sep, '/'), path
	for src, dest in (('Contrib/cbios', 'machines'), ('Contrib/cbios-old', 'systemroms/cbios-old')):
		for name in sorted(os.listdir(src)):
			path = os.path.join(src, name)
			if os.path.isfile(path):
				yield dest + '/' + name, path
	yield 'cbios.txt', 'Contrib/README.cbios'


def main(out):
	raw = bytearray()
	count = 0
	for rel, path in files():
		with open(path, 'rb') as f:
			data = f.read()
		name = rel.encode('utf-8')
		raw += len(name).to_bytes(4, 'little') + name
		raw += len(data).to_bytes(8, 'little') + data
		count += 1
	packed = zlib.compress(bytes(raw), 9)
	crc = zlib.crc32(packed)
	tmp = out + '.tmp'
	with open(tmp, 'w') as f:
		f.write('// Generated by build/libretro_share.py: %d files\n' % count)
		f.write('constexpr unsigned long shareCrc = 0x%08xUL;\n' % crc)
		f.write('constexpr unsigned long long shareRawSize = %dULL;\n' % len(raw))
		f.write('alignas(8) constexpr unsigned char shareData[] = {\n')
		for i in range(0, len(packed), 32):
			f.write(','.join(str(b) for b in packed[i:i + 32]) + ',\n')
		f.write('};\n')
	os.replace(tmp, out)


if __name__ == '__main__':
	main(sys.argv[1])
